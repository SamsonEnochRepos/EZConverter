#!/usr/bin/env python3
"""Generates docs/security/license-inventory.md from what is actually installed.

Python: importlib.metadata for ezconverter's resolved dependency closure.
JavaScript: `pnpm licenses list --json --prod` per application workspace.
External executables: detected versions plus the license each project publishes (recorded here by hand; verify on upgrade).
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def py_closure(root_name: str = "ezconverter") -> dict[str, metadata.Distribution]:
    seen: dict[str, metadata.Distribution] = {}
    todo = [root_name]
    while todo:
        n = todo.pop()
        key = re.sub(r"[-_.]+", "-", n).lower()
        if key in seen:
            continue
        try:
            d = metadata.distribution(n)
        except metadata.PackageNotFoundError:
            continue
        seen[key] = d
        for r in d.requires or []:
            if "extra ==" in r and not any(e in r for e in ("sevenzip",)):
                continue
            name = re.split(r"[ ;<>=!~\[(]", r, maxsplit=1)[0]
            todo.append(name)
    return seen


def lic(d: metadata.Distribution) -> str:
    m = d.metadata
    if m.get("License-Expression"):
        return m["License-Expression"]
    classifiers = [
        c.split("::")[-1].strip() for c in m.get_all("Classifier") or [] if c.startswith("License ::")
    ]
    if classifiers:
        return "; ".join(classifiers)
    raw = (m.get("License") or "").strip().splitlines()
    return raw[0][:80] if raw else "UNKNOWN"


def sh(*argv: str) -> str:
    try:
        return subprocess.run(argv, capture_output=True, text=True, timeout=60).stdout.strip()
    except Exception:
        return ""


def main() -> int:
    out = [
        "# Dependency and license inventory",
        "",
        "Generated by `scripts/license_inventory.py` from the installed environment. **This is an engineering inventory, not legal advice.**",
        "Resolve every item marked ⚠ before shipping a packaged build.",
        "",
        "## 1. Python runtime dependencies (backend)",
        "",
        "| Package | Version | License |",
        "|---|---|---|",
    ]
    for k, d in sorted(py_closure().items()):
        if k == "ezconverter":
            continue
        out.append(f"| {d.metadata['Name']} | {d.version} | {lic(d)} |")

    out += [
        "",
        "## 2. External executables and native libraries (invoked as separate processes)",
        "",
        "| Tool | Detected version | License | Distribution note |",
        "|---|---|---|---|",
    ]
    ff = sh("ffmpeg", "-version").splitlines()[:1]
    ffcfg = sh("ffmpeg", "-version")
    gpl = "--enable-gpl" in ffcfg
    tools = [
        (
            "FFmpeg",
            ff[0] if ff else "not installed",
            "LGPL-2.1+ / **GPL-2.0+ in this build**" if gpl else "LGPL-2.1+",
            "⚠ This build enables GPL components (libx264/libx265). Shipping it inside an app/container makes that distribution subject to GPL "
            "(source offer, notices). Alternatives: link an LGPL-only build, drop x264/x265 and use OpenH264/VP9/AV1, or require users to install FFmpeg.",
        ),
        (
            "LibreOffice",
            sh("soffice", "--version") or "not installed",
            "MPL-2.0 (+ bundled third-party components)",
            "Run as an unmodified external process. Bundled fonts carry individual licenses (SIL OFL, Apache, GPL-with-font-exception); audit before redistributing.",
        ),
        (
            "Pandoc",
            sh("pandoc", "--version").splitlines()[0] if sh("pandoc", "--version") else "not installed",
            "GPL-2.0-or-later",
            "⚠ Used only as a separate executable. Redistribution requires the GPL source offer; no linking.",
        ),
        (
            "Poppler utils (pdftoppm, pdfinfo)",
            sh("pdftoppm", "-v") or "installed (version on stderr)",
            "GPL-2.0-or-later",
            "⚠ Same as Pandoc: separate executable, GPL obligations on redistribution.",
        ),
        (
            "util-linux (prlimit, unshare)",
            sh("prlimit", "--version") or "n/a",
            "GPL-2.0+/LGPL (system tools)",
            "Present on the target OS; not redistributed.",
        ),
        (
            "Pillow codec libs (libwebp, libavif/aom/dav1d, libtiff, libjpeg-turbo, zlib)",
            "bundled in the Pillow wheel",
            "BSD-style / permissive",
            "Confirm the wheel's bundled-library notices (Pillow ships a licenses file) in packaged builds.",
        ),
        (
            "py7zr (7z support)",
            next((str(d.version) for k, d in py_closure().items() if k == "py7zr"), "not installed"),
            "LGPL-2.1-or-later",
            "⚠ Dynamic import of an unmodified pip dependency is fine; statically bundling (PyInstaller one-file) needs LGPL compliance (relinking ability).",
        ),
    ]
    for t in tools:
        out.append("| " + " | ".join(t) + " |")

    out += ["", "## 3. JavaScript production dependencies", ""]
    for app in ("web", "desktop", "mobile"):
        raw = sh("pnpm", "--filter", f"@ezconverter/{app}", "licenses", "list", "--prod", "--json")
        try:
            data = json.loads(raw)
        except ValueError:
            note = (
                "no production dependencies (Electron and the sidecar are bundled at packaging time)"
                if app == "desktop"
                else "unavailable: run `pnpm install` first"
            )
            out += [f"### {app}", "", note, ""]
            continue
        counts = {k: len(v) for k, v in data.items()}
        out += [f"### {app}", "", "| License | Packages |", "|---|---|"]
        out += [f"| {k} | {v} |" for k, v in sorted(counts.items(), key=lambda kv: -kv[1])]
        flagged = {k: v for k, v in data.items() if re.search(r"GPL|AGPL|SSPL|UNKNOWN|CC-BY-NC", k, re.I)}
        if flagged:
            out += [
                "",
                "⚠ Review:",
                *[f"- {k}: " + ", ".join(sorted({p["name"] for p in v})) for k, v in flagged.items()],
            ]
        out.append("")

    out += [
        "## 4. Development-only dependencies",
        "",
        "pytest, pytest-xdist, httpx, ruff, python-pptx, openpyxl (Python); vitest, Playwright, TypeScript, Vite, Tailwind, electron-builder, openapi-typescript (JS). "
        "They are not redistributed in packaged applications. Electron itself (MIT) bundles Chromium (BSD-style and many third-party licenses, "
        "see `LICENSES.chromium.html` inside the Electron distribution) and must ship that file with desktop builds.",
        "",
    ]
    dest = ROOT / "docs" / "security" / "license-inventory.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
