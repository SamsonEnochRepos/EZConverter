#!/usr/bin/env python3
"""Turn conformance results into the verified-capability manifest and the format-matrix docs.

Run after:  rm -rf tests/.conformance-results && pytest -m conformance -n 4
Only capabilities with a passing record are written to the manifest (and thus advertised by default).
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from ezconverter.domain.formats import FORMATS  # noqa: E402
from ezconverter.registry import default_registry  # noqa: E402
from ezconverter.registry.conformance import write_verified  # noqa: E402

FID = {
    "byte_preserving": "B",
    "lossless_reencode": "L",
    "lossy": "~",
    "layout_altering": "P",
    "semantic": "S",
}


def main() -> int:
    results: dict[str, dict] = {}
    for f in sorted((ROOT / "tests" / ".conformance-results").glob("*.jsonl")):
        for line in f.read_text().splitlines():
            r = json.loads(line)
            results[r["id"]] = r  # last write wins
    reg = default_registry()
    caps = {e.capability.id: e for e in reg.all()}
    passed = sorted(i for i, r in results.items() if r["status"] == "passed" and i in caps)
    failed = sorted(i for i, r in results.items() if r["status"] != "passed")
    untested = sorted(set(caps) - set(results))
    versions = {e["engine_id"]: e["version"] for e in reg.engines() if e["version"]}
    write_verified(passed, versions)

    out = ROOT / "docs" / "format-matrix"
    out.mkdir(parents=True, exist_ok=True)
    manifest = []
    for cid in sorted(caps):
        c = caps[cid].capability
        d = c.to_dict()
        d["verification"] = "passed" if cid in passed else ("failed" if cid in failed else "not-run")
        d["engine_available_here"] = caps[cid].availability.ok
        manifest.append(d)
    (out / "capabilities.json").write_text(
        json.dumps({"engine_versions": versions, "capabilities": manifest}, indent=1) + "\n"
    )

    by_src: dict[str, list] = defaultdict(list)
    for cid in passed:
        c = caps[cid].capability
        by_src[c.source].append(c)
    lines = [
        "# Format matrix",
        "",
        "Generated by `scripts/build_format_matrix.py` from the conformance run. **Only conversions that passed the",
        "real-engine conformance suite are listed.** Multi-step routes (for example DOCX → PNG via PDF) are computed by the",
        "planner from the composable steps below and are not listed here; query `/v1/targets` or `/v1/files/{id}/targets`.",
        "",
        "Fidelity: `B` byte-preserving · `L` lossless re-encode · `~` lossy · `P` layout-altering · `S` semantic transformation",
        "",
        f"**{len(passed)} verified direct capabilities** of {len(caps)} registered ({len(failed)} failing, {len(untested)} not run).",
        "",
    ]
    for fam in ("document", "spreadsheet", "presentation", "image", "audio", "video", "archive", "data"):
        srcs = [s for s in sorted(by_src) if FORMATS[s].family.value == fam]
        if not srcs:
            continue
        lines += [
            f"## {fam.title()}",
            "",
            "| Source | Direct targets (fidelity) | Engines |",
            "|---|---|---|",
        ]
        for s in srcs:
            ts = sorted(by_src[s], key=lambda c: c.target)
            lines.append(
                f"| {FORMATS[s].name} (`{s}`) | "
                + ", ".join(f"`{c.target}` {FID[c.fidelity.value]}" for c in ts)
                + " | "
                + ", ".join(sorted({c.engine_id for c in ts}))
                + " |"
            )
        lines.append("")
    lines += [
        "## Deliberately not supported",
        "",
        "| Conversion | Why |",
        "|---|---|",
        "| Raster image → SVG | Needs vector tracing; it would only approximate the original. |",
        "| PDF → DOCX/PPTX/XLSX/ODT… | Layout reconstruction is unreliable. PDF → TXT (text layer) and PDF → PNG/JPEG/TIFF (one page) are offered. |",
        "| Scanned PDF/image → text | OCR is not implemented. |",
        "| HEIC/HEIF images | Recognised, not decoded (no licensed decoder bundled). |",
        "| Video → image frames, audio → image | Not implemented yet. |",
        "| Password-protected PDF/ZIP/7z | Rejected with an explanation; passwords are never accepted. |",
        "",
        "## Known limitations of verified conversions",
        "",
    ]
    notes = defaultdict(set)
    for cid in passed:
        c = caps[cid].capability
        for w in c.warnings:
            notes[w].add(f"{c.source}→{c.target}")
    for w, pairs in sorted(notes.items()):
        ps = sorted(pairs)
        lines.append(
            f"- {w}  \n  _Applies to_: "
            + ", ".join(ps[:12])
            + (f" … (+{len(ps) - 12} more)" if len(ps) > 12 else "")
        )
    if failed:
        lines += ["", "## Failing capabilities (not advertised)", ""] + [
            f"- `{i}`: {results[i].get('error', '')}" for i in failed
        ]
    if untested:
        lines += ["", "## Registered but not covered by a conformance record (not advertised)", ""] + [
            f"- `{i}`" for i in untested
        ]
    (out / "README.md").write_text("\n".join(lines) + "\n")
    print(f"verified={len(passed)} failed={len(failed)} untested={len(untested)} total={len(caps)}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
